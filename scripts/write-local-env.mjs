import { existsSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const raw = execSync("supabase status -o json", { cwd: root, encoding: "utf8" });
const jsonStart = raw.indexOf("{");
const parsed = JSON.parse(raw.slice(jsonStart));

const apiUrl = parsed.API_URL ?? parsed.apiUrl ?? "http://127.0.0.1:54321";
const dbUrl =
  parsed.DB_URL ?? parsed.dbUrl ?? "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
const publishable =
  parsed.PUBLISHABLE_KEY ?? parsed.ANON_KEY ?? parsed.publishableKey ?? parsed.anonKey;
const secret =
  parsed.SECRET_KEY ?? parsed.SERVICE_ROLE_KEY ?? parsed.secretKey ?? parsed.serviceRoleKey;

if (!publishable || !secret) {
  throw new Error("supabase status did not include API keys");
}

const env = `# Generated by scripts/write-local-env.mjs. Do not commit.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
NEXT_PUBLIC_METAL_API_URL=http://127.0.0.1:4000
NEXT_PUBLIC_SITE_URL=http://localhost:3100
DATABASE_URL=${dbUrl}
SUPABASE_URL=${apiUrl}
SUPABASE_PUBLISHABLE_KEY=${publishable}
SUPABASE_SECRET_KEY=${secret}
METAL_API_URL=http://127.0.0.1:4000
LOG_LEVEL=info
METAL_ENVIRONMENT=development
CORS_ALLOWED_ORIGINS=http://127.0.0.1:3100,http://localhost:3100
API_HOST=127.0.0.1
API_PORT=4000
API_REQUEST_TIMEOUT_MS=10000
WORKER_ID=local-worker-1
WORKER_LEASE_MS=30000
WORKER_POLL_MS=250
WORKER_BATCH_SIZE=10
WORKER_MAX_ATTEMPTS=8
WORKER_BASE_BACKOFF_MS=200
`;

for (const file of [".env", "apps/web/.env.local", "apps/api/.env", "apps/worker/.env"]) {
  writeFileSync(resolve(root, file), env);
}

if (!existsSync(resolve(root, ".env.example"))) {
  throw new Error("missing .env.example");
}

console.log("Wrote local env files from supabase status.");
