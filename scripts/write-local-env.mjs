import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { resolve } from "node:path";
import { loadRootEnv, repoRoot } from "./load-root-env.mjs";

const root = repoRoot();
loadRootEnv();

const raw = execSync("supabase status -o json", { cwd: root, encoding: "utf8" });
const jsonStart = raw.indexOf("{");
const parsed = JSON.parse(raw.slice(jsonStart));

const apiUrl = parsed.API_URL ?? parsed.apiUrl ?? "http://127.0.0.1:54321";
const dbUrl =
  parsed.DB_URL ?? parsed.dbUrl ?? "postgresql://postgres:postgres@127.0.0.1:55322/postgres";
const publishable =
  parsed.PUBLISHABLE_KEY ?? parsed.ANON_KEY ?? parsed.publishableKey ?? parsed.anonKey;
const secret =
  parsed.SECRET_KEY ?? parsed.SERVICE_ROLE_KEY ?? parsed.secretKey ?? parsed.serviceRoleKey;

if (!publishable || !secret) {
  throw new Error("supabase status did not include API keys");
}

const localEnv = `# Generated by scripts/write-local-env.mjs. Do not commit.
# Machine-specific local Supabase values. Shared secrets stay in encrypted .env.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
DATABASE_URL=${dbUrl}
SUPABASE_URL=${apiUrl}
SUPABASE_PUBLISHABLE_KEY=${publishable}
SUPABASE_SECRET_KEY=${secret}
`;

const siteUrl = usableEnvValue(process.env.NEXT_PUBLIC_SITE_URL) || "http://localhost:3100";
const metalApiUrl =
  usableEnvValue(process.env.NEXT_PUBLIC_METAL_API_URL) ||
  usableEnvValue(process.env.METAL_API_URL) ||
  "http://127.0.0.1:4000";

const webEnv = `# Generated by scripts/write-local-env.mjs. Do not commit.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
NEXT_PUBLIC_METAL_API_URL=${metalApiUrl}
NEXT_PUBLIC_SITE_URL=${siteUrl}
`;

writeFileSync(resolve(root, ".env.local"), localEnv);
writeFileSync(resolve(root, "apps/web/.env.local"), webEnv);

if (!existsSync(resolve(root, ".env"))) {
  throw new Error("missing encrypted .env");
}

const supabaseEnvPath = resolve(root, "supabase/.env");
const existingSupabaseEnv = parseEnvFile(supabaseEnvPath);
const supabaseEnv = `# Generated by scripts/write-local-env.mjs from encrypted .env. Do not commit.
# Local Supabase Auth OAuth credentials. Shared values live in encrypted .env.

SUPABASE_AUTH_EXTERNAL_GOOGLE_CLIENT_ID=${envValue(
  "SUPABASE_AUTH_EXTERNAL_GOOGLE_CLIENT_ID",
  existingSupabaseEnv,
)}
SUPABASE_AUTH_EXTERNAL_GOOGLE_SECRET=${envValue(
  "SUPABASE_AUTH_EXTERNAL_GOOGLE_SECRET",
  existingSupabaseEnv,
)}
SUPABASE_AUTH_EXTERNAL_GITHUB_CLIENT_ID=${envValue(
  "SUPABASE_AUTH_EXTERNAL_GITHUB_CLIENT_ID",
  existingSupabaseEnv,
)}
SUPABASE_AUTH_EXTERNAL_GITHUB_SECRET=${envValue(
  "SUPABASE_AUTH_EXTERNAL_GITHUB_SECRET",
  existingSupabaseEnv,
)}
`;
writeFileSync(supabaseEnvPath, supabaseEnv);

console.log("Wrote machine-specific .env.local files from supabase status.");

function envValue(key, existing) {
  return usableEnvValue(process.env[key]) || usableEnvValue(existing[key]) || "";
}

function usableEnvValue(value) {
  if (!value || value.startsWith("encrypted:")) {
    return "";
  }
  return value;
}

function parseEnvFile(path) {
  if (!existsSync(path)) {
    return {};
  }

  const values = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const separator = trimmed.indexOf("=");
    if (separator <= 0) {
      continue;
    }
    const key = trimmed.slice(0, separator);
    let value = trimmed.slice(separator + 1);
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}
